// Атлас 2.0: лад орди в захопленому монстрами місті (вождь, закони, касти): текст для вікна поселення й зали вождя.
(function () {
  'use strict';
  const A = globalThis.Atlas2, pick = (r, a) => a[Math.floor(r() * a.length)];
  const TITLE = ['Вождь', 'Кістяний король', 'Матка виводку', 'Верховний шаман', 'Старійшина-пожирач', 'Володар ями'];
  const LAWS = ['Слабкі працюють у горнах і ямах, сильні ведуть.', 'Чужинця або в клітку, або в котел, залежно від настрою вождя.', 'Здобич ділять на торгу: третина вождю, третина шаманам, решта орді.', 'Нічні варти по черзі; хто заснув на посту, іде в яму.', 'Виводок священний: чіпати гнізда не можна нікому.', 'Клани б’ються лише в ямі й лише за дозволом вождя.', 'Данина м’ясом і залізом збирається щомісяця.', 'Полонених можна викупити, але лише золотом чи магічною річчю.'];
  const CASTE = ['воїни, виводок, шамани й невільники', 'ватажки, мисливці, ковалі й нероби-приживали', 'клани-вартові, жерці, жебраки-падальники й раби'];
  function make(r, s) {
    const lead = s.monsters && s.monsters[0], laws = []; while (laws.length < 3) { const l = pick(r, LAWS); if (!laws.includes(l)) laws.push(l); }
    return { chief: pick(r, TITLE) + (lead ? ' — ' + lead.name : ''), laws, caste: pick(r, CASTE) };
  }
  A.MonOrder = { make };
})();
